#!/usr/bin/env node
// Splits the system prompts in reference/ into groups using the rules in
// reference/sections.json, counts each group once with count_tokens, and writes
// the result to extension/baseline.js as fixed values.
// The prompt text never goes into the extension — only the numbers and group labels.
//
// The file name sets the model id: claude-opus-5.5.md -> claude-opus-5-5
//
// Usage: ANTHROPIC_API_KEY=... node scripts/count-baseline.mjs

import { readdir, readFile, writeFile } from "node:fs/promises";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const referenceDir = join(root, "reference");
const outFile = join(root, "extension", "baseline.js");

const apiKey = process.env.ANTHROPIC_API_KEY;
if (!apiKey) {
  console.error("ANTHROPIC_API_KEY is not set.");
  process.exit(1);
}

const config = JSON.parse(await readFile(join(referenceDir, "sections.json"), "utf8"));
const rules = config.rules.map((r) => ({ re: new RegExp(r.pattern), group: r.group }));
for (const r of rules) {
  if (!config.groups[r.group]) throw new Error(`sections.json: unknown group "${r.group}"`);
}

function groupOf(unit) {
  const rule = rules.find((r) => r.re.test(unit));
  return rule ? rule.group : config.default;
}

// Splits the prompt into units: each '# heading' is a unit; top-level headings
// listed in 'split' are split at the '## heading' level.
function splitUnits(text) {
  const units = [];
  let top = null;
  let current = null;
  for (const line of text.split("\n")) {
    const h1 = line.match(/^# (.+)$/);
    const h2 = line.match(/^## (.+)$/);
    if (h1) {
      top = h1[1].trim();
      current = { name: top, lines: [] };
      units.push(current);
    } else if (h2 && config.split.includes(top)) {
      current = { name: h2[1].trim(), lines: [] };
      units.push(current);
    }
    if (!current) {
      current = { name: "(untitled)", lines: [] };
      units.push(current);
    }
    current.lines.push(line);
  }
  return units;
}

async function countTokens(model, system) {
  const body = { model, messages: [{ role: "user", content: "." }] };
  if (system) body.system = system;
  const res = await fetch("https://api.anthropic.com/v1/messages/count_tokens", {
    method: "POST",
    headers: {
      "x-api-key": apiKey,
      "anthropic-version": "2023-06-01",
      "content-type": "application/json",
    },
    body: JSON.stringify(body),
  });
  if (!res.ok) throw new Error(`${model}: ${res.status} ${await res.text()}`);
  return (await res.json()).input_tokens;
}

const files = (await readdir(referenceDir)).filter((f) => f.endsWith(".md"));
if (!files.length) {
  console.error("No .md files in reference/.");
  process.exit(1);
}

const models = {};
for (const file of files) {
  const model = basename(file, ".md").replaceAll(".", "-");
  const text = await readFile(join(referenceDir, file), "utf8");

  const texts = {};
  const sections = {};
  for (const unit of splitUnits(text)) {
    const g = groupOf(unit.name);
    (texts[g] ??= []).push(unit.lines.join("\n"));
    (sections[g] ??= []).push(unit.name);
  }

  // Count with and without the text; the difference is the text's own tokens.
  const empty = await countTokens(model, null);
  const groups = {};
  for (const [g, parts] of Object.entries(texts)) {
    const def = config.groups[g];
    const tokens = (await countTokens(model, parts.join("\n"))) - empty;
    groups[g] = {
      label: def.label,
      flag: def.flag || null,
      kind: def.kind || null,
      tokens,
      sections: sections[g].length,
    };
  }
  const total = (await countTokens(model, text)) - empty;
  models[model] = { file, total, groups };

  console.log(`${model} (${file}): ${total} tokens total`);
  for (const [g, v] of Object.entries(groups)) {
    const tag = v.flag ? `flag: ${v.flag}` : v.kind || "always";
    console.log(`  ${String(v.tokens).padStart(7)}  ${v.label} [${tag}] — ${v.sections} sections`);
  }
}

const baseline = { countedAt: new Date().toISOString().slice(0, 10), models };
await writeFile(
  outFile,
  "// Generated by scripts/count-baseline.mjs — do not edit by hand.\n" +
    `globalThis.CTS_BASELINE = ${JSON.stringify(baseline, null, 2)};\n`
);
console.log(`Wrote ${outFile}`);
